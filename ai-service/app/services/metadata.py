import io
from typing import List, Tuple
from PIL import Image
import numpy as np
from pydantic import BaseModel, Field


class MetadataSuggestionResult(BaseModel):
    category: str = Field(..., description="High-level garment category, e.g., TOPS, BOTTOMS, DRESSES, OUTERWEAR, SHOES, ACCESSORIES")
    subCategory: str = Field(..., description="Specific garment type, e.g., t-shirt, jeans, jacket, dress")
    color: str = Field(..., description="Dominant color name, e.g., Navy Blue, Black, White, etc.")
    pattern: str = Field(..., description="Visual pattern, e.g., solid, striped, plaid, graphic")
    fit: str = Field(..., description="Estimated fit, e.g., regular, slim, oversized")
    season: str = Field(..., description="Recommended season, e.g., SUMMER, WINTER, ALL_SEASON")
    confidence: float = Field(..., description="Model confidence score between 0.0 and 1.0")
    detectedTags: List[str] = Field(default_factory=list, description="Descriptive tags extracted from visual analysis")
    isAiGenerated: bool = Field(default=True, description="Flag indicating if the metadata was generated by AI")


